export const inRect = (x: number, z: number, r: Rect, m = 0) => x > r[0] - m && x < r[1] + m && z > r[2] - m && z < r[3] + m

export function isBlocked(x: number, z: number, margin = 2) {
  for (const r of FOOTPRINTS) if (inRect(x, z, r, margin)) return true
  for (const r of PAVED) if (inRect(x, z, r, margin * 0.5)) return true
  for (const r of ROADS) if (inRect(x, z, r, margin)) return true
  return false
}
