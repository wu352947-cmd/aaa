const OPENING: Record<string, (label: string) => string> = {
  card: (l) => `你做了「${l}」。会议室里的事，最后都落到了盘面上。`,
  'wash-trade': () => '你对敲出来的成交量挂在行情软件上。有人看见量放大了，以为“险资还在买”，跟了进去。',
  spoofing: () => '你挂了又撤的那些大单，让盘口看起来很厚。有人照着它下了单。',
  'marking-close': () => '收盘价是你做出来的。质押的平仓线、基金的净值，都按它算。',
  bylaw: () => '你悄悄改了议事规则。小股东手里的那一票，从此轻了一截。',
};

export function victimTakeover(g: Game, deed: DarkDeed): Victim | null {
  const p = pick(g, deed, PEOPLE);
  if (!p) return null;
  return letterFrom(
    g,
    p,
    (OPENING[deed.cause] ?? OPENING.card)(deed.label),
    (x) => `${x.toLocaleString()} 元`,
    (f) => `${(f / 100).toFixed(2)} 元`,
  );
}
