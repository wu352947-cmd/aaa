/** 一天：给几个锚点，中间用受约束的布朗桥连起来 */
function day(
  date: string,
  label: string,
  kind: DayDef['kind'],
  pts: [string, number][],
  vDay: number,
  sigma: number,
  noise: number,
  halfLife = 45,
  crowdShare = 0.45,
): DayDef {
  return {
    date,
    label,
    kind,
    hist: bridgePath(
      pts.map(([t, p]) => [Math.min(L - 1, Math.max(0, m(t))), Math.round(p * 100)]),
      L,
      noise,
      `hk-${date}`,
    ),
    vDay,
    sigma,
    halfLife,
    crowdShare,
    provenance: 'reconstructed',
  };
}

